"""Regenerate src/card-study/index.ts from the card studies in src/card-study/*.json.

Card studies live in this repo (src/card-study/, one <card id>.json each plus intro.json); write or edit them there,
then run: python3 scripts/sync_card_study.py
The printable booklet: python3 scripts/card-study/build_booklet.py
"""
from pathlib import Path

dst = Path(__file__).resolve().parent.parent / 'src' / 'card-study'
cards = sorted(p.stem for p in dst.glob('*.json') if p.stem != 'intro')
lines = ['// Generated by scripts/sync_card_study.py. Do not edit.', "import intro from './intro.json';"]
lines += [f"import {c} from './{c}.json';" for c in cards]
lines += ['', 'export const INTRO = intro;', f'export const CARDS: Record<string, unknown> = {{ {", ".join(cards)} }};', '']
(dst / 'index.ts').write_text('\n'.join(lines))
print(f'{len(cards)} cards:', ', '.join(cards))
