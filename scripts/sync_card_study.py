"""Copy card-study data from the library repo into the app and regenerate src/card-study/index.ts.

Usage: python3 scripts/sync_card_study.py [path to ios_202610.familiar_library]
"""
import shutil, sys
from pathlib import Path

app = Path(__file__).resolve().parent.parent
lib = Path(sys.argv[1] if len(sys.argv) > 1 else app.parent / 'ios_202610.familiar_library') / 'card-study'
dst = app / 'src' / 'card-study'
dst.mkdir(exist_ok=True)
for old in dst.glob('*.json'):
    old.unlink()
cards = sorted(p.stem for p in lib.glob('*.json') if p.stem != 'intro')
for name in ['intro', *cards]:
    shutil.copy(lib / f'{name}.json', dst / f'{name}.json')
lines = ['// Generated by scripts/sync_card_study.py. Do not edit.', "import intro from './intro.json';"]
lines += [f"import {c} from './{c}.json';" for c in cards]
lines += ['', 'export const INTRO = intro;', f'export const CARDS: Record<string, unknown> = {{ {", ".join(cards)} }};', '']
(dst / 'index.ts').write_text('\n'.join(lines))
print(f'{len(cards)} cards:', ', '.join(cards))
